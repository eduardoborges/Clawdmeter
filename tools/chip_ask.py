#!/usr/bin/env python3
"""Writes firmware/src/ask_pcm.h, the sound for "Claude Code asks for permission".

8-bit take on a question-mark sting: G dim7 (G A# C# E) an octave above G4,
NES-style arpeggio (one note per 1/30 s), triangle wave, stepped 4-bit volume
that holds 0.15 s and then decays. Usage: python3 tools/chip_ask.py
"""
import struct
from pathlib import Path

SR = 44100
NOTES = [783.99, 932.33, 1108.73, 1318.51]
FRAME = SR // 30
DUR = 0.75
FADE_IN = int(0.003 * SR)   # no click at the start

pcm = bytearray()
phase = 0.0
for i in range(int(SR * DUR)):
    phase = (phase + NOTES[(i // FRAME) % 4] / SR) % 1
    tri = 4 * abs(phase - 0.5) - 1
    vol = max(0, 15 - int(max(i / SR - 0.15, 0) / 0.04)) / 15
    x = tri * vol * 0.85 * min(1, i / FADE_IN)
    s = int(x * 32767)
    pcm += struct.pack('<hh', s, s)

out = Path(__file__).resolve().parent.parent / 'firmware/src/ask_pcm.h'
with out.open('w') as f:
    f.write('#pragma once\n#include <stdint.h>\n\n')
    f.write('// "ask" clip PCM, generated by tools/chip_ask.py (see there for the sound).\n')
    f.write('// 44.1 kHz, 16-bit, stereo, little-endian.\n')
    f.write('static const uint8_t ask_pcm[] = {\n')
    for i in range(0, len(pcm), 20):
        f.write('  ' + ','.join(str(b) for b in pcm[i:i + 20]) + ',\n')
    f.write('};\n')
    f.write(f'static const unsigned int ask_pcm_len = {len(pcm)};\n')
